const { ConfigService } = require('@nestjs/config')
const { PrismaService } = require('../dist/prisma/prisma.service.js')
const { StorageQuotaService } = require('../dist/modules/storage/storage-quota.service.js')
const { LocalStorageAdapter } = require('../dist/modules/storage/local-storage.service.js')
const { VideoProcessingService } = require('../dist/modules/resources/video-processing.service.js')
const database = new URL(process.env.DATABASE_URL || 'file:///missing')
if (database.hostname !== '127.0.0.1' || database.port !== '55440' || database.pathname !== '/media_runtime') throw new Error('只允许隔离媒体验收数据库')
const prisma = new PrismaService(), config = new ConfigService()
const quota = new StorageQuotaService(prisma, config), storage = new LocalStorageAdapter(prisma, config, quota)
const processor = new VideoProcessingService(prisma, config, storage, quota)
async function stop() { await processor.onModuleDestroy(); await quota.onModuleDestroy(); await storage.onModuleDestroy(); await prisma.$disconnect(); process.exit(0) }
process.once('SIGTERM', () => { stop().catch(() => process.exit(1)) })
process.once('SIGINT', () => { stop().catch(() => process.exit(1)) })
prisma.$connect().then(async () => { quota.onModuleInit(); storage.onModuleInit(); await processor.onModuleInit(); console.log('合成媒体工作进程已启动') }).catch(() => process.exit(1))
